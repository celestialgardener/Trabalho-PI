    private void btnbuscaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbuscaActionPerformed
       // busca o cliente e sua compra
       String idcli = txtidcli.getText();
       if (idcli.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Digite algum id para buscar");
         return;
        }
       String sql = "SELECT p.id_pedido, c.nome " +
             "FROM Pedido p " +
             "INNER JOIN Cliente c ON p.id_cliente = c.id_cliente " +
             "WHERE c.id_cliente = ?";

    try (Connection conn = new conexao().getConnection();
     PreparedStatement stmt = conn.prepareStatement(sql)) {

    stmt.setInt(1, Integer.parseInt(idcli));

    try (ResultSet rs = stmt.executeQuery()) {

        DefaultTableModel modelo = (DefaultTableModel) tbl.getModel();
        modelo.setRowCount(0);

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("id_pedido"),
                rs.getString("nome")
            });
        }

        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Nenhum pedido encontrado.");
        }
    }

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "O ID precisa ser um número.");
} catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao buscar.\n" + ex.getMessage());
}
       
       
       
       
    }//GEN-LAST:event_btnbuscaActionPerformed

    private void btnmostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnmostrarActionPerformed

    String sql = "SELECT c.id_cliente, c.nome, c.email, "
               + "COUNT(p.id_pedido) AS qtd_pedidos, "
               + "SUM(p.valor_total) AS total_gasto "
               + "FROM Cliente c "
               + "JOIN Pedido p ON p.id_cliente = c.id_cliente "
               + "GROUP BY c.id_cliente, c.nome, c.email "
               + "ORDER BY qtd_pedidos DESC";

    try (java.sql.Connection conn = new conexao().getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
            new Object[]{"ID", "Nome", "Email", "Pedidos", "Total gasto"}, 0);

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("id_cliente"),
                rs.getString("nome"),
                rs.getString("email"),
                rs.getInt("qtd_pedidos"),
                rs.getBigDecimal("total_gasto")
            });
        }
        tbl2.setModel(modelo);

        if (modelo.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Nenhum cliente com pedido.");
        }

    } catch (java.sql.SQLException | ClassNotFoundException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro na consulta.\n" + ex.getMessage());
    }

    }//GEN-LAST:event_btnmostrarActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
           String idcli = txtidcli.getText();
       if (idcli.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Digite algum id para buscar");
         return;
        }
    int idCli;
    try {
        idCli = Integer.parseInt(txtidcli.getText().trim());
    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "O id do cliente precisa ser um número.");
        return;
    }

    String sql = "SELECT c.nome, p.id_pedido, p.data_pedido, p.status, p.valor_total, "
               + "AVG(p.valor_total) OVER (PARTITION BY c.id_cliente) AS media_por_pedido "
               + "FROM Cliente c "
               + "JOIN Pedido p ON p.id_cliente = c.id_cliente "
               + "WHERE c.id_cliente = ? "
               + "ORDER BY p.data_pedido DESC";

    try (java.sql.Connection conn = new conexao().getConnection();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, idCli);

        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
                new Object[]{"Cliente", "Pedido", "Data", "Status", "Valor", "Média por pedido"}, 0);

            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getString("nome"),
                    rs.getInt("id_pedido"),
                    rs.getTimestamp("data_pedido"),
                    rs.getString("status"),
                    rs.getBigDecimal("valor_total"),
                    rs.getBigDecimal("media_por_pedido")
                });
            }
            tbl3.setModel(modelo);

            if (modelo.getRowCount() == 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Esse cliente não existe ou não tem pedidos");
            }
        }

    } catch (java.sql.SQLException | ClassNotFoundException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro na consulta.\n" + ex.getMessage());
    }
 
       
       
    }//GEN-LAST:event_jButton1ActionPerformed

