    private void btnsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsalvarActionPerformed
        String cnpj = txtcnpj.getText().trim();
        String nome = txtnome.getText().trim();
        String razao = txtrazaosocial.getText().trim();
        String email = txtemail.getText().trim();
        String telefone = txttelefone.getText().trim();
        String cep = txtcep.getText().trim();
        String logradouro = txtlogradouro.getText().trim();
        String numero = txtnumero.getText().trim();
        String bairro = txtbairro.getText().trim();
        String cidade = txtcidade.getText().trim();
        String estado = txtestado.getText().trim();
        String complemento = txtcomplemento.getText().trim();
        
        
        // validar campos vazios
    if (cnpj.isEmpty() || nome.isEmpty() || razao.isEmpty() || complemento.isEmpty()|| email.isEmpty() || telefone.isEmpty()||cep.isEmpty() ||
            logradouro.isEmpty()||numero.isEmpty() ||bairro.isEmpty() ||cidade.isEmpty() ||estado.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Preencha todos os campos");
        return;
    }
    
    
    
    // Comando SQL para inserir o produto no banco
    String sql = "INSERT INTO Fornecedor (razao_social, nome_fantasia, cnpj, email, telefone, logradouro, numero, complemento, bairro, cidade,estado, cep) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";
    
    
    try (Connection conn = new conexao().getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql)) {
        //a ordem *TEM QUE SER ESSA*  senão manda as iformações nos campos errados, sempre faça na ordem que ta no bd 
        stmt.setString(1, razao);        // razao_social
        stmt.setString(2, nome);         // nome_fantasia
        stmt.setString(3, cnpj);         // cnpj
        stmt.setString(4, email);        // email
        stmt.setString(5, telefone);     // telefone
        stmt.setString(6, logradouro);   // logradouro
        stmt.setString(7, numero);       // numero
        stmt.setString(8, complemento);  // complemento
        stmt.setString(9, bairro);       // bairro
        stmt.setString(10, cidade);      // cidade
        stmt.setString(11, estado);      // estado
        stmt.setString(12, cep);         // cep

        stmt.executeUpdate();


        // limpar os campos
        txtcnpj.setText("");
        txtnome.setText("");
        txtrazaosocial.setText("");
        txtemail.setText("");
        txttelefone.setText("");
        txtcep.setText("");
        txtlogradouro.setText("");
        txtnumero.setText("");
        txtbairro.setText("");
        txtcidade.setText("");
        txtestado.setText("");
        txtcomplemento.setText("");

        JOptionPane.showMessageDialog(this, "vendedor cadastrado com sucesso!");

    } catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro: " + ex.getMessage());
    }
    
    
    
    
    
    
    
    }//GEN-LAST:event_btnsalvarActionPerformed

