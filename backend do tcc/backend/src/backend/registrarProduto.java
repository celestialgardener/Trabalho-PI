    private void btnsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsalvarActionPerformed
        // pegar os dados do form
    String id_forn = txtID_vendedor.getText().trim();
    String nome = txtNome.getText().trim();
    String descricao = txtDescricao.getText().trim();
    String categoria = txtCategoria.getText().trim();
    String marca = txtMarca.getText().trim();
    String valor = txtPreco.getText().trim();
    String quantia = txtEstoque.getText().trim();
    
    // se algum campo estiver vazio isso aqui avisa 
    if (id_forn.isEmpty() || nome.isEmpty() || descricao.isEmpty() || categoria.isEmpty() || marca.isEmpty()|| valor.isEmpty() || quantia.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Preencha todos os campos");
        return;
    }
    
        // converter valor e quantia e id para numeros
    double preco;
    int estoque;
    int id_fornecedor;
    try {
        preco = Double.parseDouble(valor.replace(",", "."));
        estoque = Integer.parseInt(quantia);
        id_fornecedor = Integer.parseInt(id_forn);
    } catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "Preço e estoque e id fornecedor precisam ser números válidos");
    txtPreco.setText("");
    txtEstoque.setText("");
    txtID_vendedor.setText("");
    return;
    }
    // se nada deu pau ate aqui, daqui pra frente ele manda 
    // Comando SQL para inserir o produto no banco
    //lembre de colocar na ORDEM CERTA ISSO AQUI EM BAIXO, igualzinho como esta no banco 
    String sql = "INSERT INTO Produto (id_fornecedor, nome, descricao, categoria, marca, preco, estoque) VALUES (?, ?, ?, ?, ?, ?, ?)";
    
       
    try (Connection conn = new conexao().getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql)) {
        //a ordem *TEM QUE SER ESSA* 
        stmt.setInt(1, id_fornecedor);       
        stmt.setString(2, nome);        
        stmt.setString(3, descricao);        
        stmt.setString(4, categoria);       
        stmt.setString(5, marca);     
        stmt.setDouble(6, preco);   
        stmt.setInt(7, estoque);       


        stmt.executeUpdate();


        // limpar os campos
        txtID_vendedor.setText("");
        txtNome.setText("");
        txtDescricao.setText("");
        txtCategoria.setText("");
        txtMarca.setText("");
        txtPreco.setText("");
        txtEstoque.setText("");

        JOptionPane.showMessageDialog(this, "produto cadastrado com sucesso!");

    } catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao salvar. Confira se o ID do fornecedor existe.\n" + ex.getMessage());
    }
    
    
    
    }//GEN-LAST:event_btnsalvarActionPerformed

