    private void btnbuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbuscarActionPerformed
String idven = txtidven.getText().trim();
if (idven.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Digite algum id para buscar");
    return;
}

String sql = "SELECT f.id_fornecedor, p.nome, p.estoque " +
             "FROM Produto p " +
             "INNER JOIN Fornecedor f ON p.id_fornecedor = f.id_fornecedor " +
             "WHERE f.id_fornecedor = ?";

try (Connection conn = new conexao().getConnection();
     PreparedStatement stmt = conn.prepareStatement(sql)) {

    stmt.setInt(1, Integer.parseInt(idven));

    try (ResultSet rs = stmt.executeQuery()) {

        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"ID fornecedor", "Produto", "Estoque"}, 0);

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("id_fornecedor"),
                rs.getString("nome"),
                rs.getInt("estoque")
            });
        }
        tbl.setModel(modelo);

        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Nenhum produto encontrado.");
        }
    }

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "O ID precisa ser um número.");
} catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao buscar.\n" + ex.getMessage());
}
    }//GEN-LAST:event_btnbuscarActionPerformed

    private void btnbuscarhavingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbuscarhavingActionPerformed

String sql = "SELECT f.id_fornecedor, f.nome_fantasia " +
             "FROM Fornecedor f " +
             "INNER JOIN Produto p ON p.id_fornecedor = f.id_fornecedor " +
             "GROUP BY f.id_fornecedor, f.nome_fantasia " +
             "HAVING COUNT(p.id_produto) >= 2";

try (Connection conn = new conexao().getConnection();
     PreparedStatement stmt = conn.prepareStatement(sql)) {

    try (ResultSet rs = stmt.executeQuery()) {

        DefaultTableModel modelo = new DefaultTableModel(
           new Object[]{"ID", "Nome fantasia"}, 0);

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("id_fornecedor"),
                rs.getString("nome_fantasia")
            });
        }
        tbl.setModel(modelo);

        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Nenhum fornecedor encontrado.");
        }
    }

} catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao buscar.\n" + ex.getMessage());
}  
    }//GEN-LAST:event_btnbuscarhavingActionPerformed

    private void btnBaratoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBaratoActionPerformed
        String sql = "SELECT f.nome_fantasia, MAX(p.preco) AS mais_caro, MIN(p.preco) AS mais_barato "
                   + "FROM Fornecedor f "
                + "JOIN Produto p ON p.id_fornecedor = f.id_fornecedor "
                + "GROUP BY f.id_fornecedor, f.nome_fantasia";

        try (Connection conn = new conexao().getConnection();
     PreparedStatement stmt = conn.prepareStatement(sql)) {

         try (ResultSet rs = stmt.executeQuery()) {

        // define as 3 colunas (substitui o modelo antigo da tabela)
        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"Fornecedor", "Maior preço", "Menor preço"}, 0);

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getString("nome_fantasia"),
                rs.getBigDecimal("mais_caro"),
                rs.getBigDecimal("mais_barato")
            });
        }
        tbl.setModel(modelo);

        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Nenhum fornecedor encontrado.");
        }
         }

        } catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao buscar.\n" + ex.getMessage());
        }
    }//GEN-LAST:event_btnBaratoActionPerformed

    private void btnCategoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCategoriaActionPerformed

    String sql = "SELECT categoria, COUNT(*) AS qtd_produtos, AVG(preco) AS preco_medio "
               + "FROM Produto "
               + "GROUP BY categoria";

    try (Connection conn = new conexao().getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql)) {

        try (ResultSet rs = stmt.executeQuery()) {

            DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"Categoria", "Qtd de produtos", "Preço medio"}, 0);

            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getString("categoria"),
                    rs.getInt("qtd_produtos"),
                    rs.getBigDecimal("preco_medio")
                });
            }
            tbl.setModel(modelo);

            if (modelo.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this, "Nenhum produto cadastrado.");
            }
        }

    } catch (SQLException | ClassNotFoundException ex) {
        JOptionPane.showMessageDialog(this, "Erro ao buscar.\n" + ex.getMessage());
    }

    }//GEN-LAST:event_btnCategoriaActionPerformed

