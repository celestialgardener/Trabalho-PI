    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
   // pegar os dados do form
String nome = txtNome.getText().trim();
String email = txtEmail.getText().trim();
String senha = txtSenha.getText().trim();
String cpf = txtCpf.getText().trim();
String telefone = txtTelefone.getText().trim();
String logradouro = txtLogradouro.getText().trim();
String numero = txtNumero.getText().trim();
String complemento = txtComplemento.getText().trim();
String bairro = txtBairro.getText().trim();
String cidade = txtCidade.getText().trim();
String estado = txtEstado.getText().trim();
String cep = txtCep.getText().trim();

// se algum campo estiver vazio isso aqui avisa
if (nome.isEmpty() || email.isEmpty() || senha.isEmpty() || cpf.isEmpty() || telefone.isEmpty()
        || logradouro.isEmpty() || numero.isEmpty() || complemento.isEmpty() || bairro.isEmpty()
        || cidade.isEmpty() || estado.isEmpty() || cep.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Preencha todos os campos");
    return;
}

// se nada deu pau ate aqui, daqui pra frente ele manda
// Comando SQL para inserir o cliente no banco
// lembre de colocar na ORDEM CERTA ISSO AQUI EM BAIXO, igualzinho como esta no banco
String sql = "INSERT INTO Cliente (nome, email, senha, cpf, telefone, logradouro, numero, complemento, bairro, cidade, estado, cep) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

try (Connection conn = new conexao().getConnection();
     PreparedStatement stmt = conn.prepareStatement(sql)) {

    // a ordem *TEM QUE SER ESSA*
    stmt.setString(1, nome);
    stmt.setString(2, email);
    stmt.setString(3, senha);
    stmt.setString(4, cpf);
    stmt.setString(5, telefone);
    stmt.setString(6, logradouro);
    stmt.setString(7, numero);
    stmt.setString(8, complemento);
    stmt.setString(9, bairro);
    stmt.setString(10, cidade);
    stmt.setString(11, estado);
    stmt.setString(12, cep);

    stmt.executeUpdate();

    // limpar os campos
    txtNome.setText("");
    txtEmail.setText("");
    txtSenha.setText("");
    txtCpf.setText("");
    txtTelefone.setText("");
    txtLogradouro.setText("");
    txtNumero.setText("");
    txtComplemento.setText("");
    txtBairro.setText("");
    txtCidade.setText("");
    txtEstado.setText("");
    txtCep.setText("");

    JOptionPane.showMessageDialog(this, "Cliente cadastrado com sucesso!");

} catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao salvar o cliente.\n" + ex.getMessage());
}
    }//GEN-LAST:event_btnSalvarActionPerformed

