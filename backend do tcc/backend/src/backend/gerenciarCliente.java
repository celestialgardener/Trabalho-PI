    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed

    String Idcli = txtIdcli.getText().trim();

    if (Idcli.isEmpty()) {
     JOptionPane.showMessageDialog(this, "Digite o ID do cliente para buscar.");
     return;
    }

    String sql = "SELECT id_cliente, nome, email, senha, cpf, telefone, " +
                 "logradouro, numero, complemento, bairro, cidade, estado, cep " +
                 "FROM Cliente WHERE id_cliente = ?";

    try (Connection conn = new conexao().getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, Integer.parseInt(Idcli));

        try (ResultSet rs = stmt.executeQuery()) {

            DefaultTableModel modelo = (DefaultTableModel) tblResultado.getModel();
            modelo.setRowCount(0);

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("id_cliente"),
                rs.getString("nome"),
                rs.getString("email"),
                rs.getString("senha"),
                rs.getString("cpf"),
                rs.getString("telefone"),
                rs.getString("logradouro"),
                rs.getString("numero"),
                rs.getString("complemento"),
                rs.getString("bairro"),
                rs.getString("cidade"),
                rs.getString("estado"),
                rs.getString("cep")
            });
        }

        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Nenhum cliente encontrado com esse ID.");
        }
      }

        } catch (NumberFormatException ex) {
          JOptionPane.showMessageDialog(this, "O ID precisa ser um número.");
        } catch (SQLException | ClassNotFoundException ex) {
           JOptionPane.showMessageDialog(this, "Erro ao buscar.\n" + ex.getMessage());
        }

    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed

String Idcli = txtIdcli.getText().trim();
String nome = txtNome.getText().trim();
String email = txtEmail.getText().trim();
String senha = txtSenha.getText().trim();
String cpf = txtCpf.getText().trim();
String telefone = txtTelefone.getText().trim();
String logradouro = txtLogradouro.getText().trim();
String numero = txtNumero.getText().trim();
String complemento = txtComplemento.getText().trim();
String bairro = txtBairro.getText().trim();
String cidade = txtCidade.getText().trim();
String estado = txtEstado.getText().trim();
String cep = txtCep.getText().trim();

if (Idcli.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Digite o ID do cliente para editar.");
    return;
}

if (numero.isEmpty() || cep.isEmpty() || nome.isEmpty() ||
    email.isEmpty() || senha.isEmpty() || cpf.isEmpty() ||
    telefone.isEmpty() || logradouro.isEmpty() ||
    complemento.isEmpty() || bairro.isEmpty() ||
    cidade.isEmpty() || estado.isEmpty()) {

    JOptionPane.showMessageDialog(this, "Preencha todos os campos antes de atualizar o cliente.");
    return;
}

int id;

try {
    id = Integer.parseInt(Idcli);
} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "O ID precisa ser um número válido.");
    return;
}

String sql = "UPDATE Cliente SET nome = ?, email = ?, senha = ?, " +
             "cpf = ?, telefone = ?, logradouro = ?, numero = ?, " +
             "complemento = ?, bairro = ?, cidade = ?, estado = ?, cep = ? " +
             "WHERE id_cliente = ?";

try (Connection conn = new conexao().getConnection();
     PreparedStatement stmt = conn.prepareStatement(sql)) {

    stmt.setString(1, nome);
    stmt.setString(2, email);
    stmt.setString(3, senha);
    stmt.setString(4, cpf);
    stmt.setString(5, telefone);
    stmt.setString(6, logradouro);
    stmt.setString(7, numero);
    stmt.setString(8, complemento);
    stmt.setString(9, bairro);
    stmt.setString(10, cidade);
    stmt.setString(11, estado);
    stmt.setString(12, cep);
    stmt.setInt(13, id);

    int linhasAfetadas = stmt.executeUpdate();

    if (linhasAfetadas > 0) {
        JOptionPane.showMessageDialog(this, "Cliente atualizado com sucesso!");
    } else {
        JOptionPane.showMessageDialog(this, "Nenhum cliente encontrado com esse ID.");
    }

} catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao atualizar.\n" + ex.getMessage());
}


    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnDeletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletarActionPerformed
        //primeiro faz o termo de busca virar uma string
        String IdProduto = txtIdcli.getText().trim();
        //verifica campo esta preenchido
        if (IdProduto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o id de um  cliente para buscar");
            return;
        }

        int id;
        try {
            id = Integer.parseInt(IdProduto);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "O ID precisa ser um numero");
            return;
        }

        // ese painel do jopatin mostra uma escolha sim ou não pra voce não errar
        int confirmacao = JOptionPane.showConfirmDialog(this,
            "você tem certeza absoluta que quer excluir o cliente " + id + " do nosso banco de dados?",
            "Confirmar",
            JOptionPane.YES_NO_OPTION);

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM Cliente WHERE id_cliente = ?";

        try (Connection conn = new conexao().getConnection();
            PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setInt(1, id);

            int linhasAfetadas = stmt.executeUpdate();

            if (linhasAfetadas > 0) {
                JOptionPane.showMessageDialog(this, "Cliente excluido!");
            } else {
                JOptionPane.showMessageDialog(this, "não encontrei cliente com esse ID");
            }

        } catch (SQLException | ClassNotFoundException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao excluir.\n" + ex.getMessage());
        }

    }//GEN-LAST:event_btnDeletarActionPerformed

