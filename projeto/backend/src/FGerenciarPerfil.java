    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        // TODO add your handling code here:
        String sql = "UPDATE cliente SET nome = ?, email = ?, senha = ?, telefone = ?, "
               + "logradouro = ?, numero = ?, complemento = ?, bairro = ?, "
               + "cidade = ?, estado = ?, cep = ? "
               + "WHERE id_cliente = ?";

        try (Connection conn = new Conexao().getConnection();
            PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, txtNome.getText().trim());
            ps.setString(2, txtEmail.getText().trim());
            ps.setString(3, txtSenha.getText().trim());
            ps.setString(4, txtTelefone.getText().trim());
            ps.setString(5, txtRua.getText().trim());
            ps.setString(6, txtNumero.getText().trim());
            ps.setString(7, txtComplemento.getText().trim());
            ps.setString(8, txtBairro.getText().trim());
            ps.setString(9, txtCidade.getText().trim());
            ps.setString(10, txtEstado.getText().trim());
            ps.setString(11, txtCEP.getText().trim());
            ps.setInt(12, idClienteLogado);   // id vindo do login / da tela anterior

            int linhasAfetadas = ps.executeUpdate();

            if (linhasAfetadas > 0) {
                JOptionPane.showMessageDialog(this, "Perfil atualizado com sucesso!");
            } else {
                JOptionPane.showMessageDialog(this, "Nenhum registro foi atualizado.");
            }

        } catch (SQLException e) {
            // email é UNIQUE: erro 2627 / 2601 no SQL Server = duplicidade
            if (e.getErrorCode() == 2627 || e.getErrorCode() == 2601) {
                JOptionPane.showMessageDialog(this, "Este e-mail já está em uso por outro cliente.");
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao atualizar: " + e.getMessage());
            }
        } catch (ClassNotFoundException e) {
        JOptionPane.showMessageDialog(this, "Driver do SQL Server não encontrado: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAtualizarActionPerformed

