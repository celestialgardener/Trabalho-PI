    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
            //primeiro faz o termo de busca virar uma string, nesse caso é a categoria  
        String Nome = txtNomeBusca.getText().trim();
        //verifica se pelo menos um cmapo esta preenchido
        if (Nome.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Digite algo para buscar");
         return;
        }
        // ai vem o string do sql, igual no outro arquivo mesma coisa MAS, o query e diferente 
        String sql = "SELECT id_produto, id_fornecedor, nome, descricao, categoria, marca, preco, estoque "+ "FROM Produto WHERE LOWER(nome) LIKE ?"; 
        
        //conecta pa
         try (Connection conn = new conexao().getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql)) {
             
        stmt.setString(1, "%" + Nome.toLowerCase() + "%"); //essa linha faz com que o ? do query vire o nome da categoria, esse comando 
        // tambem ja deixa em lowercase e ve se tem a categoria no nome pra ficar mais facil
        // tem que importar import java.sql.ResultSet;
        try (ResultSet rs = stmt.executeQuery()) {

            DefaultTableModel modelo = (DefaultTableModel) tblResultadoBusca.getModel();
            modelo.setRowCount(0); // limpa resultado anterior

            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getInt("id_produto"),
                    rs.getInt("id_fornecedor"),
                    rs.getString("nome"),
                    rs.getString("descricao"),
                    rs.getString("categoria"),
                    rs.getString("marca"),
                    rs.getBigDecimal("preco"),
                    rs.getInt("estoque")
                });
            }

            if (modelo.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this, "Nenhum produto encontrado nessa categoria.");
            }
        }

    } catch (SQLException | ClassNotFoundException ex) {
        JOptionPane.showMessageDialog(this, "Erro ao buscar.\n" + ex.getMessage());
    }
    
    }//GEN-LAST:event_jButton1ActionPerformed

    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
       // NESSA CASO PRECISAMOS IMPORTAR import java.math.RoundingMode; import java.math.BigDecimal; e import java.sql.Statement; PRA SALVAR O RESULTADO COMO VARIAVEL 

        //eu ja vou usar o sum pra fazer a conta pelo banco de dados, primeiro preciso pegar o produto e seu valor, depois criar o carrinho na tabela pedido
       // por fim colocar o produto na tabela item pedido associada a esse pedido 
        
       String IdBusca = txtIdBusca.getText();
       String IdCliente = txtIdCli.getText();
       String Quantia = txtQuantia.getText();
       if (IdBusca.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Digite algo para adicionar ao carrinho");
         return;
        }
       
       
       if (IdCliente.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Digite Seu ID de cliente");
         return;
        }
       
       int idCli;
       try{
           idCli = Integer.parseInt(IdCliente);
       } catch (NumberFormatException e){
       JOptionPane.showMessageDialog(this, "o ID do cliente precisa ser um numero");
            return;
       }
       
       
       
       int id;
        try {
        id = Integer.parseInt(IdBusca);
        } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "o ID do produto precisa ser um numero");
            return;
     }
       
       
       
        int qnt;
        try {
        qnt = Integer.parseInt(Quantia);
        } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "a quantia precisa ser um numero");
            return;
     }
       
        // passo 1: o querie de fazer a conta 
        //pegar o valor do produto, multiplicar pela quantidade 

        String sql = "SELECT (preco*?) as total "+ "FROM Produto WHERE id_produto = ?";
        BigDecimal total = null;
        try (Connection conn = new conexao().getConnection();
        PreparedStatement stmt = conn.prepareStatement(sql)) {

             stmt.setInt(1, qnt);
             stmt.setInt(2, id);

    try (ResultSet rs = stmt.executeQuery()) {
        if (rs.next()) {
            total = rs.getBigDecimal("total");   // a variavel total é quanto o cliente vai pagar nessa quantia de produtos
        } else {
            JOptionPane.showMessageDialog(this, "Produto não encontrado.");
            return;
        }
    }
            
    } catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao calcular.\n" + ex.getMessage());
    return;
    }
        //passo 2: id da tabela de pedidos
    // agora que peguei o valor do produto eu posso criar uma partezinha na tabela de Pedidos que depois vou atualizar com o item 
    String sql2 = "INSERT INTO Pedido (id_cliente,data_pedido,valor_total,status) VALUES (?, GETDATE(), ?, ?)";
    int idPedido = 0;
    try (Connection conn = new conexao().getConnection();
        PreparedStatement stmt = conn.prepareStatement(sql2, Statement.RETURN_GENERATED_KEYS)) {  //parte necessaria pra guardar qual pedido esse ´~e 
        stmt.setInt(1, idCli);
        stmt.setBigDecimal(2,total); // eu fiquei um bom tempo pra descobrir que isso e possivel
        stmt.setString(3, "Aberto");

        stmt.executeUpdate();

        try (ResultSet rs = stmt.getGeneratedKeys()) {
            if (rs.next()) {
                idPedido = rs.getInt(1);
            }
        }

    } catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao calcular.\n" + ex.getMessage());
    return;
    }
        
        
        
        
        
//passo 3:
     //agora que temos o valor que ele vai pagar e o id na tabela Pedidos, na tabela item pedidos colocamos a quantia de itens, o valor do pedido dividio pela quantia 
     //e o id do produto e o id de pedido, o id de item é auto incerement  
     
    BigDecimal valorUni = total.divide(BigDecimal.valueOf(qnt), 2, RoundingMode.HALF_UP);

    String sql3 = "INSERT INTO Item_Pedido (id_pedido,id_produto,quantidade,preco_unitario) VALUES (?, ?, ?, ?)";
    try (Connection conn = new conexao().getConnection();
        PreparedStatement stmt = conn.prepareStatement(sql3)) {  //parte necessaria pra guardar qual pedido esse ´~e 
        stmt.setInt(1, idPedido); 
        stmt.setInt(2, id);
        stmt.setInt(3, qnt);
        stmt.setBigDecimal(4, valorUni);

        stmt.executeUpdate();

    } catch (SQLException | ClassNotFoundException ex) {
    JOptionPane.showMessageDialog(this, "Erro ao calcular.\n" + ex.getMessage());
    return;
    }
     
     
     

     
     
    }//GEN-LAST:event_btnAdicionarActionPerformed

